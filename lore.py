def boss_name(act_index):
    bid = BOSS_BY_ACT[act_index] if act_index < len(BOSS_BY_ACT) else BOSS_BY_ACT[0]
    return ENEMY_DEFS.get(bid, {}).get("name", "Страж")


def completed_act_name(act_index):
    if 0 <= act_index < len(ACTS):
        return ACTS[act_index]["name"]
    return "Рубеж"


def get_act_transition(new_act_index):
    entry = ACT_TRANSITIONS.get(new_act_index)
    if not entry:
        return None
    completed = new_act_index - 1
    data = dict(entry)
    data["completed_act"] = completed
    data["completed_name"] = completed_act_name(completed)
    data["boss_line"] = data["boss_line"].format(boss=boss_name(completed))
    data["new_act_name"] = completed_act_name(new_act_index) if new_act_index < len(ACTS) else ACTS[-1]["name"]
    return data


def get_defeat_lore(act_index):
    return DEFEAT_LORE.get(act_index, "Рубеж ждёт следующего стража.")
